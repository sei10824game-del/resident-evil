package com.reevil.entity;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.effect.MobEffect;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.projectile.Arrow;
import net.minecraft.world.phys.Vec3;

import java.util.*;
import java.util.function.Consumer;
import java.util.function.Predicate;

/**
 * Data-driven extra moves (ids 40+) and passives (mutations, regeneration) for original-game abilities that the base classes lack.
 * Registered in {@link CanonData} (generated by tools/canon_moves.py); the model side is client/canon/CanonClips.
 */
public final class CanonMoves {
    @FunctionalInterface public interface Fx { void run(BioMonster s, LivingEntity t); }
    private record TickFx(int from, int to, Fx fx) {}

    public static final class Def {
        public final AttackMove move;
        Predicate<BioMonster> can = s -> true;
        final List<TickFx> ticks = new ArrayList<>();
        final Map<Integer, List<Fx>> hits = new HashMap<>();
        final List<Fx> start = new ArrayList<>(), end = new ArrayList<>();
        boolean noDefault;
        Def(AttackMove m) { move = m; }
        public Def can(Predicate<BioMonster> p) { can = p; return this; }
        public Def tick(int a, int b, Fx f) { ticks.add(new TickFx(a, b, f)); return this; }
        public Def hit(int i, Fx... f) { hits.computeIfAbsent(i, k -> new ArrayList<>()).addAll(Arrays.asList(f)); return this; }
        public Def onStart(Fx f) { start.add(f); return this; }
        public Def onEnd(Fx f) { end.add(f); return this; }
        public Def noDefault() { noDefault = true; return this; }
    }

    private static final Map<String, List<Def>> DEFS = new HashMap<>();
    private static final Map<String, List<Consumer<BioMonster>>> PASSIVES = new HashMap<>();
    private static final Map<List<AttackMove>, Map<String, List<AttackMove>>> MERGED = new IdentityHashMap<>();
    static { CanonData.register(); }

    // ------------------------------------------------------------------ registry
    public static Def add(String entity, AttackMove m) { Def d = new Def(m); DEFS.computeIfAbsent(entity, k -> new ArrayList<>()).add(d); return d; }
    public static void passive(String entity, Consumer<BioMonster> p) { PASSIVES.computeIfAbsent(entity, k -> new ArrayList<>()).add(p); }

    static String key(BioMonster s) { return BuiltInRegistries.ENTITY_TYPE.getKey(s.getType()).getPath(); }
    private static Def find(BioMonster s, AttackMove m) {
        List<Def> l = DEFS.get(key(s));
        if (l != null) for (Def d : l) if (d.move == m) return d;
        return null;
    }

    public static synchronized List<AttackMove> merge(BioMonster s, List<AttackMove> base) {
        List<Def> l = DEFS.get(key(s));
        if (l == null || base.size() < 2) return base;
        return MERGED.computeIfAbsent(base, b -> new HashMap<>()).computeIfAbsent(key(s), k -> { List<AttackMove> r = new ArrayList<>(base); for (Def d : l) r.add(d.move); return List.copyOf(r); });
    }

    // ------------------------------------------------------------------ dispatch from BioMonster
    public static boolean can(BioMonster s, AttackMove m) { Def d = find(s, m); return d == null || d.can.test(s); }
    public static void start(BioMonster s, AttackMove m) { Def d = find(s, m); if (d != null) for (Fx f : d.start) f.run(s, s.getTarget()); }
    public static void end(BioMonster s, AttackMove m) { Def d = find(s, m); if (d != null) for (Fx f : d.end) f.run(s, s.getTarget()); }
    public static void tick(BioMonster s, AttackMove m, int t, LivingEntity target) {
        Def d = find(s, m); if (d == null) return;
        for (TickFx x : d.ticks) if (t >= x.from && t <= x.to) x.fx.run(s, target);
    }
    public static void hit(BioMonster s, AttackMove m, int i, LivingEntity target) {
        Def d = find(s, m); if (d == null) return;
        if (!d.noDefault && target != null && s.distanceTo(target) <= m.maxRange + 0.8 + target.getBbWidth() * 0.5) s.strike(target, m.damage, m.knockback);
        List<Fx> l = d.hits.get(i);
        if (l != null) for (Fx f : l) f.run(s, target);
    }
    public static void passives(BioMonster s) {
        List<Consumer<BioMonster>> l = PASSIVES.get(key(s));
        if (l != null) for (Consumer<BioMonster> p : l) p.accept(s);
    }

    // ------------------------------------------------------------------ conditions
    public static Predicate<BioMonster> hpBelow(float f) { return s -> s.getHealth() < s.getMaxHealth() * f; }
    public static Predicate<BioMonster> mut(int n) { return s -> s.getMut() == n; }
    public static Predicate<BioMonster> mutAny() { return s -> s.getMut() > 0; }

    // ------------------------------------------------------------------ passives
    public static Consumer<BioMonster> mutateAt(float hpFrac, int... options) {
        return s -> {
            if (s.level().isClientSide || s.getMut() != 0 || !s.isAlive() || s.getHealth() >= s.getMaxHealth() * hpFrac) return;
            s.cancelMove();
            s.setMut(options[s.getRandom().nextInt(options.length)]);
            s.playVoice("attack", 1.2f);
            ((ServerLevel) s.level()).sendParticles(ParticleTypes.EXPLOSION, s.getX(), s.getY() + s.getBbHeight() * 0.5, s.getZ(), 2, 0.3, 0.3, 0.3, 0);
        };
    }
    public static Consumer<BioMonster> regen(float perSecondFrac) {
        return s -> { if (!s.level().isClientSide && s.isAlive() && s.tickCount % 20 == 0 && !s.isOnFire() && s.getHealth() < s.getMaxHealth()) s.heal(s.getMaxHealth() * perSecondFrac); };
    }

    // ------------------------------------------------------------------ effects
    public static Fx lunge(double h, double v) { return (s, t) -> s.lunge(h, v); }
    public static Fx strike(float dmg, double kb, double reach) { return (s, t) -> { if (t != null && s.distanceTo(t) <= reach + t.getBbWidth() * 0.5) s.strike(t, dmg, kb); }; }
    public static Fx launch(double vy) { return (s, t) -> { if (t != null && s.distanceTo(t) < 6) { t.push(0, vy, 0); t.hurtMarked = true; } }; }
    public static Fx effect(MobEffect e, int ticks, int amp) { return (s, t) -> { if (t != null && s.distanceTo(t) < 7) t.addEffect(new MobEffectInstance(e, ticks, amp), s); }; }
    public static Fx selfEffect(MobEffect e, int ticks, int amp) { return (s, t) -> s.addEffect(new MobEffectInstance(e, ticks, amp)); }
    public static Fx fire(int sec) { return (s, t) -> { if (t != null && s.distanceTo(t) < 7) t.setSecondsOnFire(sec); }; }
    public static Fx heal(float amount) { return (s, t) -> s.heal(amount); }
    public static Fx mutate(int n) { return (s, t) -> s.setMut(n); }
    public static Fx pull(double strength) {
        return (s, t) -> {
            if (t == null) return;
            Vec3 d = s.position().subtract(t.position()).multiply(1, 0, 1).normalize().scale(strength);
            t.push(d.x, 0.25, d.z); t.hurtMarked = true;
        };
    }
    public static Fx blink() {
        return (s, t) -> {
            if (t == null) return;
            Vec3 back = Vec3.directionFromRotation(0, t.getYRot()).scale(-1.7);
            s.teleportTo(t.getX() + back.x, t.getY(), t.getZ() + back.z);
            s.getNavigation().stop();
        };
    }
    public static Fx aoe(double r, float dmg, double kb) {
        return (s, t) -> {
            for (LivingEntity e : s.level().getEntitiesOfClass(LivingEntity.class, s.getBoundingBox().inflate(r), x -> x != s && x.isAlive() && Factions.hostile(s, x))) {
                if (s.distanceTo(e) > r + e.getBbWidth() * 0.5) continue;
                if (e.hurt(s.damageSources().mobAttack(s), dmg)) {
                    Vec3 d = e.position().subtract(s.position()).multiply(1, 0, 1).normalize().scale(kb);
                    e.push(d.x, 0.35, d.z); e.hurtMarked = true;
                }
            }
        };
    }
    /** damage (and optional burning) to everything hostile in a 70-degree cone in front. */
    public static Fx cone(double range, float dmg, int fireSec) {
        return (s, t) -> {
            Vec3 look = Vec3.directionFromRotation(0, s.getYRot());
            for (LivingEntity e : s.level().getEntitiesOfClass(LivingEntity.class, s.getBoundingBox().inflate(range), x -> x != s && x.isAlive() && Factions.hostile(s, x))) {
                Vec3 d = e.position().subtract(s.position()).multiply(1, 0, 1);
                if (d.length() > range || d.length() < 1.0e-3 || d.normalize().dot(look) < 0.34) continue;
                if (e.hurt(s.damageSources().mobAttack(s), dmg) && fireSec > 0) e.setSecondsOnFire(fireSec);
            }
            if (s.level() instanceof ServerLevel sl && fireSec > 0)
                sl.sendParticles(ParticleTypes.FLAME, s.getX() + look.x * 1.5, s.getY() + s.getBbHeight() * 0.6, s.getZ() + look.z * 1.5, 6, 0.6, 0.2, 0.6, 0.02);
        };
    }
    /** ranged arrow-like shot with an optional effect on hit: kinds arrow, poison, slow, fire. */
    public static Fx shot(String kind, float dmg) {
        return (s, t) -> {
            if (t == null || s.level().isClientSide) return;
            Arrow a = new Arrow(s.level(), s);
            a.setBaseDamage(dmg / 2.0);
            if (kind.equals("poison")) a.addEffect(new MobEffectInstance(net.minecraft.world.effect.MobEffects.POISON, 100, 1));
            if (kind.equals("slow")) a.addEffect(new MobEffectInstance(net.minecraft.world.effect.MobEffects.MOVEMENT_SLOWDOWN, 80, 1));
            if (kind.equals("fire")) a.setSecondsOnFire(6);
            a.setPos(s.getX(), s.getEyeY() - 0.2, s.getZ());
            double dx = t.getX() - s.getX(), dy = t.getEyeY() - a.getY(), dz = t.getZ() - s.getZ();
            a.shoot(dx, dy + Math.sqrt(dx * dx + dz * dz) * 0.04, dz, 2.0f, 2.0f);
            s.level().addFreshEntity(a);
        };
    }
    public static Fx summon(String id, int n) {
        return (s, t) -> {
            if (s.level().isClientSide) return;
            EntityType<?> type = BuiltInRegistries.ENTITY_TYPE.get(new ResourceLocation("reevil", id));
            long near = s.level().getEntitiesOfClass(BioMonster.class, s.getBoundingBox().inflate(14), x -> x.getType() == type).size();
            for (int i = 0; i < n && near + i < 7; i++) {
                Entity e = type.create(s.level());
                if (e == null) return;
                double a = s.getRandom().nextDouble() * Math.PI * 2;
                e.moveTo(s.getX() + Math.cos(a) * 2.5, s.getY(), s.getZ() + Math.sin(a) * 2.5, s.getRandom().nextFloat() * 360f, 0);
                if (e instanceof net.minecraft.world.entity.Mob m && t != null) m.setTarget(t);
                s.level().addFreshEntity(e);
            }
        };
    }

    private CanonMoves() {}
}
