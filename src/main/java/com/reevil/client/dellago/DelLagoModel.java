import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the NeptuneModel rig, so all clips apply, with replaced/added parts. */
public class DelLagoModel extends NeptuneModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "del_lago"), "main");
    public DelLagoModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = NeptuneModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").addOrReplaceChild("limbL-6", CubeListBuilder.create()
            .texOffs(0, 128).addBox(0, -2, -2, 10, 4, 4)
            .texOffs(28, 128).addBox(9, -1, -3, 3, 4, 6),
            PartPose.offsetAndRotation(7, 3, -6, 0, 0, 0.5f));
        root.getChild("body").addOrReplaceChild("limbR-6", CubeListBuilder.create()
            .texOffs(46, 128).addBox(-10, -2, -2, 10, 4, 4)
            .texOffs(74, 128).addBox(-12, -1, -3, 3, 4, 6),
            PartPose.offsetAndRotation(-7, 3, -6, 0, 0, -0.5f));
        root.getChild("body").addOrReplaceChild("limbL7", CubeListBuilder.create()
            .texOffs(92, 128).addBox(0, -2, -2, 10, 4, 4)
            .texOffs(0, 138).addBox(9, -1, -3, 3, 4, 6),
            PartPose.offsetAndRotation(7, 3, 7, 0, 0, 0.5f));
        root.getChild("body").addOrReplaceChild("limbR7", CubeListBuilder.create()
            .texOffs(18, 138).addBox(-10, -2, -2, 10, 4, 4)
            .texOffs(46, 138).addBox(-12, -1, -3, 3, 4, 6),
            PartPose.offsetAndRotation(-7, 3, 7, 0, 0, -0.5f));
        root.getChild("body").getChild("head").addOrReplaceChild("barbel", CubeListBuilder.create()
            .texOffs(64, 138).addBox(-6.5f, 1, -13, 1, 1, 8)
            .texOffs(82, 138).addBox(5.5f, 1, -13, 1, 1, 8)
            .texOffs(100, 138).addBox(-6.5f, -1, -10, 1, 1, 8)
            .texOffs(0, 148).addBox(5.5f, -1, -10, 1, 1, 8),
            PartPose.ZERO);
        root.getChild("body").getChild("head").addOrReplaceChild("eyes", CubeListBuilder.create()
            .texOffs(18, 148).addBox(-6.5f, -7, -7, 3, 3, 3)
            .texOffs(30, 148).addBox(3.5f, -7, -7, 3, 3, 3),
            PartPose.ZERO);
        root.getChild("body").addOrReplaceChild("spikes", CubeListBuilder.create()
            .texOffs(42, 148).addBox(-1, -9, -8, 2, 3, 2)
            .texOffs(50, 148).addBox(-1, -9, -4, 2, 3, 2)
            .texOffs(58, 148).addBox(-1, -9, 0, 2, 3, 2)
            .texOffs(66, 148).addBox(-1, -9, 4, 2, 3, 2)
            .texOffs(74, 148).addBox(-1, -9, 8, 2, 3, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 160);
    }
}
