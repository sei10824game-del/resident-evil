package com.reevil.client.reaper;

import com.reevil.ReEvilMod;
import com.reevil.client.licker.LickerModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the LickerModel rig, so all clips apply, with replaced/added parts. */
public class ReaperModel extends LickerModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "reaper"), "main");
    public ReaperModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = LickerModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").addOrReplaceChild("shell", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-5, -6, -10.5f, 10, 3, 12)
            .texOffs(44, 64).addBox(-4, -8, -9, 8, 3, 9)
            .texOffs(78, 64).addBox(-6, -4, -9, 2, 5, 8)
            .texOffs(98, 64).addBox(4, -4, -9, 2, 5, 8),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").addOrReplaceChild("mand", CubeListBuilder.create()
            .texOffs(0, 79).addBox(-5, -2, -9, 2, 2, 7)
            .texOffs(18, 79).addBox(3, -2, -9, 2, 2, 7)
            .texOffs(36, 79).addBox(-1, -8, -7, 2, 3, 4),
            PartPose.ZERO);
        root.getChild("base").addOrReplaceChild("shellb", CubeListBuilder.create()
            .texOffs(48, 79).addBox(-4, -5, -2, 8, 3, 8)
            .texOffs(80, 79).addBox(-1, -8, 0, 2, 4, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
