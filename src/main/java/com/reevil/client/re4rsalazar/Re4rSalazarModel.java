package com.reevil.client.re4rsalazar;

import com.reevil.ReEvilMod;
import com.reevil.client.salazar.SalazarModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the SalazarModel rig, so all clips apply, with replaced/added parts. */
public class Re4rSalazarModel extends SalazarModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re4r_salazar"), "main");
    public Re4rSalazarModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = SalazarModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("stem1").addOrReplaceChild("leaf0", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").addOrReplaceChild("leaf1", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").addOrReplaceChild("leaf2", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").addOrReplaceChild("leaf3", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").getChild("stem2").getChild("head").addOrReplaceChild("petalT", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").getChild("stem2").getChild("head").addOrReplaceChild("petalB", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").getChild("stem2").getChild("head").addOrReplaceChild("petalL", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").getChild("stem2").getChild("head").addOrReplaceChild("petalR", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("stem1").getChild("stem2").addOrReplaceChild("head", CubeListBuilder.create()
            .texOffs(0, 256).addBox(-6, -12, -6, 12, 12, 12)
            .texOffs(48, 256).addBox(-7, -14, -7, 14, 3, 14)
            .texOffs(104, 256).addBox(-5, -18, -1, 2, 5, 2)
            .texOffs(112, 256).addBox(-1, -19, -1, 2, 6, 2)
            .texOffs(120, 256).addBox(3, -18, -1, 2, 5, 2)
            .texOffs(128, 256).addBox(-7, -6, -3, 2, 6, 6)
            .texOffs(144, 256).addBox(5, -6, -3, 2, 6, 6),
            PartPose.offset(0, -22, 0));
        root.getChild("base").getChild("stem1").addOrReplaceChild("stem2", CubeListBuilder.create()
            .texOffs(160, 256).addBox(-6, -24, -6, 12, 24, 12)
            .texOffs(0, 292).addBox(-8, -12, -8, 16, 8, 16),
            PartPose.offset(0, -28, 0));
        root.getChild("base").addOrReplaceChild("stem1", CubeListBuilder.create()
            .texOffs(64, 292).addBox(-9, -28, -8, 18, 28, 16)
            .texOffs(132, 292).addBox(-1, -26, -8.3f, 2, 26, 1),
            PartPose.offset(0, -5, 0));
        return LayerDefinition.create(mesh, 256, 336);
    }
}
