package com.reevil.client.palehead;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class PaleHeadModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "pale_head"), "main");
    public PaleHeadModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("dome", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-3.5f, -12, -3.5f, 7, 7, 7)
            .texOffs(28, 64).addBox(-4, -9, -4, 8, 2, 8),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("fangs", CubeListBuilder.create()
            .texOffs(60, 64).addBox(-2.5f, 0, -5.8f, 1, 2, 1)
            .texOffs(64, 64).addBox(1.5f, 0, -5.8f, 1, 2, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
