package com.reevil.client.saddler;

import com.reevil.ReEvilMod;
import com.reevil.client.nemesis.NemesisModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the NemesisModel rig, so all clips apply, with replaced/added parts. */
public class SaddlerModel extends NemesisModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "saddler"), "main");
    public SaddlerModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = NemesisModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").addOrReplaceChild("robe", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-5.5f, -1, -3.5f, 11, 7, 7)
            .texOffs(36, 64).addBox(-6.5f, 6, -4.5f, 13, 10, 9)
            .texOffs(80, 64).addBox(-1, -1, -4.6f, 2, 15, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("hood", CubeListBuilder.create()
            .texOffs(86, 64).addBox(-4.5f, -8.5f, -1, 9, 9, 5.5f)
            .texOffs(116, 64).addBox(-4.5f, -8.5f, -4.5f, 1.5f, 7, 4)
            .texOffs(0, 83).addBox(3, -8.5f, -4.5f, 1.5f, 7, 4)
            .texOffs(12, 83).addBox(-4, -9.5f, -4.5f, 8, 1.5f, 6)
            .texOffs(40, 83).addBox(-0.5f, -11.5f, -1, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("collar", CubeListBuilder.create()
            .texOffs(44, 83).addBox(-6, -12.5f, -3, 12, 3, 6)
            .texOffs(80, 83).addBox(-4.5f, -9, -2.6f, 9, 5, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
