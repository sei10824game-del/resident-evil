/** Own silhouette (generated by tools/variantgen.py): the NeptuneModel rig, so all clips apply, with replaced/added parts. */
public class MoreauModel extends NeptuneModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "moreau"), "main");
    public MoreauModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = NeptuneModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").addOrReplaceChild("armL", CubeListBuilder.create()
            .texOffs(0, 128).addBox(0, -2, -2, 4, 13, 4)
            .texOffs(16, 128).addBox(0, 10, -2.5f, 5, 3, 5)
            .texOffs(36, 128).addBox(1, 12, -2, 1, 5, 1)
            .texOffs(40, 128).addBox(3, 12, -2, 1, 5, 1),
            PartPose.offsetAndRotation(7, 0, -6, 0, 0, 0.4f));
        root.getChild("body").addOrReplaceChild("armR", CubeListBuilder.create()
            .texOffs(44, 128).addBox(-4, -2, -2, 4, 13, 4)
            .texOffs(60, 128).addBox(-5, 10, -2.5f, 5, 3, 5)
            .texOffs(80, 128).addBox(-5, 12, -2, 1, 5, 1)
            .texOffs(84, 128).addBox(-3, 12, -2, 1, 5, 1),
            PartPose.offsetAndRotation(-7, 0, -6, 0, 0, -0.4f));
        root.getChild("body").getChild("head").addOrReplaceChild("sac", CubeListBuilder.create()
            .texOffs(88, 128).addBox(-4, 2, -9, 8, 6, 6),
            PartPose.ZERO);
        root.getChild("body").getChild("head").addOrReplaceChild("eyes", CubeListBuilder.create()
            .texOffs(0, 145).addBox(-7, -7, -8, 4, 4, 4)
            .texOffs(16, 145).addBox(3, -7, -8, 4, 4, 4),
            PartPose.ZERO);
        root.getChild("body").addOrReplaceChild("pust", CubeListBuilder.create()
            .texOffs(32, 145).addBox(-5, -8, -4, 3, 3, 3)
            .texOffs(44, 145).addBox(3, -8, 0, 4, 3, 3)
            .texOffs(58, 145).addBox(-2, -8, 5, 3, 3, 3)
            .texOffs(70, 145).addBox(-6, -4, 8, 3, 3, 3),
            PartPose.ZERO);
        root.getChild("body").getChild("tail1").addOrReplaceChild("legs", CubeListBuilder.create()
            .texOffs(82, 145).addBox(-6, 4, -2, 3, 9, 3)
            .texOffs(94, 145).addBox(3, 4, -2, 3, 9, 3),
            PartPose.ZERO);
        root.getChild("body").getChild("head").addOrReplaceChild("maw", CubeListBuilder.create()
            .texOffs(0, 157).addBox(-8, -4, -16, 16, 3, 10)
            .texOffs(52, 157).addBox(-8, 3, -16, 16, 3, 10)
            .texOffs(104, 157).addBox(-3, -1, -14, 6, 5, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 176);
    }
}
