package com.reevil.client.re3rhunterbeta;

import com.reevil.ReEvilMod;
import com.reevil.client.hunterbeta.HunterBetaModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the HunterBetaModel rig, so all clips apply, with replaced/added parts. */
public class Re3rHunterBetaModel extends HunterBetaModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re3r_hunter_beta"), "main");
    public Re3rHunterBetaModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = HunterBetaModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("hips").getChild("chest").addOrReplaceChild("armor", CubeListBuilder.create()
            .texOffs(0, 128).addBox(-8, -14, -4, 16, 5, 9)
            .texOffs(50, 128).addBox(-9, -13, -3, 3, 7, 7)
            .texOffs(70, 128).addBox(6, -13, -3, 3, 7, 7)
            .texOffs(90, 128).addBox(-4, -9, 4, 8, 7, 3),
            PartPose.ZERO);
        root.getChild("base").getChild("hips").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("spines", CubeListBuilder.create()
            .texOffs(112, 128).addBox(-1, -7, -3, 2, 3, 2)
            .texOffs(120, 128).addBox(-1, -6.5f, 0, 2, 3, 2)
            .texOffs(0, 142).addBox(-3.5f, -6.5f, -2, 2, 3, 2)
            .texOffs(8, 142).addBox(1.5f, -6.5f, -2, 2, 3, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 152);
    }
}
