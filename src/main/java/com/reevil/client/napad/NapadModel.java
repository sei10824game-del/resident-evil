package com.reevil.client.napad;

import com.reevil.ReEvilMod;
import com.reevil.client.licker.LickerModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the LickerModel rig, so all clips apply, with replaced/added parts. */
public class NapadModel extends LickerModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "napad"), "main");
    public NapadModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = LickerModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("armL").getChild("foreL").getChild("handL").addOrReplaceChild("scythe", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-0.5f, 0, -12, 1, 3, 14)
            .texOffs(30, 64).addBox(-0.5f, 0, -16, 1, 2, 5),
            PartPose.offsetAndRotation(0, 2, -2, 0.2f, 0, 0));
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("scythe", CubeListBuilder.create()
            .texOffs(42, 64).addBox(-0.5f, 0, -12, 1, 3, 14)
            .texOffs(72, 64).addBox(-0.5f, 0, -16, 1, 2, 5),
            PartPose.offsetAndRotation(0, 2, -2, 0.2f, 0, 0));
        root.getChild("base").getChild("torso").addOrReplaceChild("spines", CubeListBuilder.create()
            .texOffs(84, 64).addBox(-1, -7, -9, 2, 4, 2)
            .texOffs(92, 64).addBox(-1, -7, -6, 2, 5, 2)
            .texOffs(100, 64).addBox(-1, -7, -3, 2, 6, 2)
            .texOffs(108, 64).addBox(-1, -6, 0, 2, 4, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").addOrReplaceChild("snout", CubeListBuilder.create()
            .texOffs(0, 81).addBox(-2.5f, -3, -13, 5, 4, 6)
            .texOffs(22, 81).addBox(-3.5f, -7, -2, 2, 4, 2)
            .texOffs(30, 81).addBox(1.5f, -7, -2, 2, 4, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
