package com.reevil.client.miranda;

import com.reevil.ReEvilMod;
import com.reevil.client.nemesis.NemesisModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the NemesisModel rig, so all clips apply, with replaced/added parts. */
public class MirandaModel extends NemesisModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "miranda"), "main");
    public MirandaModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = NemesisModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").addOrReplaceChild("robe", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-6.5f, -1, -4, 13, 7, 8)
            .texOffs(42, 64).addBox(-7.5f, 6, -5, 15, 10, 10)
            .texOffs(92, 64).addBox(-5, -1, -4.5f, 10, 2, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("hair", CubeListBuilder.create()
            .texOffs(0, 84).addBox(-4, -8, -1, 8, 12, 5)
            .texOffs(26, 84).addBox(-4, -8, -4, 8, 2, 4)
            .texOffs(50, 84).addBox(-3, -3, 4, 6, 12, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("mantle", CubeListBuilder.create()
            .texOffs(66, 84).addBox(-6.5f, -12, -3.5f, 13, 4, 7)
            .texOffs(0, 101).addBox(-5.5f, -9, -3, 11, 3, 6),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 112);
    }
}
