package com.reevil.client.kipepeo;

import com.reevil.ReEvilMod;
import com.reevil.client.giantmoth.GiantMothModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GiantMothModel rig, so all clips apply, with replaced/added parts. */
public class KipepeoModel extends GiantMothModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "kipepeo"), "main");
    public KipepeoModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GiantMothModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").addOrReplaceChild("thorax", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-3, -3, -3.5f, 6, 6, 7),
            PartPose.ZERO);
        root.getChild("body").getChild("wingL").getChild("wingOutL").addOrReplaceChild("tail", CubeListBuilder.create()
            .texOffs(26, 64).addBox(8, -0.5f, 3, 2, 1, 10),
            PartPose.ZERO);
        root.getChild("body").getChild("wingR").getChild("wingOutR").addOrReplaceChild("tail", CubeListBuilder.create()
            .texOffs(50, 64).addBox(-10, -0.5f, 3, 2, 1, 10),
            PartPose.ZERO);
        root.getChild("body").getChild("wingL").addOrReplaceChild("spotL", CubeListBuilder.create()
            .texOffs(74, 64).addBox(3, -0.7f, -2, 5, 1, 5),
            PartPose.ZERO);
        root.getChild("body").getChild("wingR").addOrReplaceChild("spotR", CubeListBuilder.create()
            .texOffs(94, 64).addBox(-8, -0.7f, -2, 5, 1, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
