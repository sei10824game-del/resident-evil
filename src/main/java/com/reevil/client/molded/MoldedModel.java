package com.reevil.client.molded;

import com.reevil.ReEvilMod;
import com.reevil.client.ganado.GanadoModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GanadoModel rig, so all clips apply, with replaced/added parts. */
public class MoldedModel extends GanadoModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "molded"), "main");
    public MoldedModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GanadoModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("mass", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -8, -4, 8, 2, 8)
            .texOffs(32, 64).addBox(-4.5f, -6, -4.5f, 3, 6, 3)
            .texOffs(44, 64).addBox(-1.5f, -9, -2, 3, 4, 3),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("mold", CubeListBuilder.create()
            .texOffs(56, 64).addBox(-6.5f, -11, -2.5f, 3, 4, 5)
            .texOffs(72, 64).addBox(3.5f, -10, -2.5f, 3, 3, 5)
            .texOffs(88, 64).addBox(-1, -11, 2, 2, 6, 3)
            .texOffs(98, 64).addBox(-4, -9, 2, 2, 5, 3)
            .texOffs(108, 64).addBox(2, -9, 2, 2, 5, 3),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
