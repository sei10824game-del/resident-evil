package com.reevil.client.zealot;

import com.reevil.ReEvilMod;
import com.reevil.client.ganado.GanadoModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GanadoModel rig, so all clips apply, with replaced/added parts. */
public class ZealotModel extends GanadoModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "zealot"), "main");
    public ZealotModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GanadoModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").addOrReplaceChild("robe", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-5, -1.5f, -2.5f, 10, 8, 5)
            .texOffs(30, 64).addBox(-6, 5, -3, 12, 7, 6),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("hood", CubeListBuilder.create()
            .texOffs(66, 64).addBox(-4.5f, -8, -1, 9, 9, 5)
            .texOffs(94, 64).addBox(-4.5f, -8, -4.5f, 1.5f, 7, 4)
            .texOffs(106, 64).addBox(3, -8, -4.5f, 1.5f, 7, 4)
            .texOffs(0, 78).addBox(-4, -9, -4.5f, 8, 1.5f, 6),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("sash", CubeListBuilder.create()
            .texOffs(28, 78).addBox(-4.5f, -10.5f, -2.5f, 9, 3, 5)
            .texOffs(56, 78).addBox(-4.4f, -7, -2.5f, 1, 7, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
