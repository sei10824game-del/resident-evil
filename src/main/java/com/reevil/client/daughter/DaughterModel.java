package com.reevil.client.daughter;

import com.reevil.ReEvilMod;
import com.reevil.client.licker.LickerModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the LickerModel rig, so all clips apply, with replaced/added parts. */
public class DaughterModel extends LickerModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "daughter"), "main");
    public DaughterModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = LickerModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").addOrReplaceChild("t1", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").getChild("t1").addOrReplaceChild("t2", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").getChild("t1").getChild("t2").addOrReplaceChild("t3", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").getChild("t1").getChild("t2").getChild("t3").addOrReplaceChild("t4", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").getChild("t1").getChild("t2").getChild("t3").getChild("t4").addOrReplaceChild("t5", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").getChild("jaw").getChild("t1").getChild("t2").getChild("t3").getChild("t4").getChild("t5").addOrReplaceChild("t6", CubeListBuilder.create(), PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").addOrReplaceChild("hair", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4.5f, -5, -0.5f, 9, 8, 6)
            .texOffs(30, 64).addBox(-4, -3, 5, 8, 2, 9)
            .texOffs(64, 64).addBox(-3, -8, -4, 6, 3, 8),
            PartPose.ZERO);
        root.getChild("base").addOrReplaceChild("skirt", CubeListBuilder.create()
            .texOffs(0, 78).addBox(-6, -3, -4, 12, 9, 13)
            .texOffs(50, 78).addBox(-7, 2, -5, 14, 3, 15),
            PartPose.offsetAndRotation(0, -1, -1, 0.1f, 0, 0));
        root.getChild("base").getChild("torso").addOrReplaceChild("dress", CubeListBuilder.create()
            .texOffs(0, 100).addBox(-4.5f, -4.5f, -10.5f, 9, 8, 11)
            .texOffs(40, 100).addBox(-5, -5, -10.5f, 10, 1, 4),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").addOrReplaceChild("fangL", CubeListBuilder.create()
            .texOffs(68, 100).addBox(-2.5f, 1, -8.4f, 1, 3, 1)
            .texOffs(72, 100).addBox(1.5f, 1, -8.4f, 1, 3, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 120);
    }
}
