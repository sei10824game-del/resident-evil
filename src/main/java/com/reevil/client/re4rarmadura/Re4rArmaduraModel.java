package com.reevil.client.re4rarmadura;

import com.reevil.ReEvilMod;
import com.reevil.client.armadura.ArmaduraModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ArmaduraModel rig, so all clips apply, with replaced/added parts. */
public class Re4rArmaduraModel extends ArmaduraModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re4r_armadura"), "main");
    public Re4rArmaduraModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ArmaduraModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("helm", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4.5f, -7, -4.5f, 9, 8, 9)
            .texOffs(36, 64).addBox(-1, -10, -4, 2, 3, 8)
            .texOffs(56, 64).addBox(-3, -4, -4.6f, 6, 1, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("plate", CubeListBuilder.create()
            .texOffs(70, 64).addBox(-5, -6, -3, 10, 6, 1)
            .texOffs(92, 64).addBox(-5, -6, 2, 10, 6, 1)
            .texOffs(0, 81).addBox(-8, -7, -3, 3, 3, 6)
            .texOffs(18, 81).addBox(5, -7, -3, 3, 3, 6),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("leftArm").getChild("leftForearm").addOrReplaceChild("shield", CubeListBuilder.create()
            .texOffs(36, 81).addBox(2, -6, -5, 2, 14, 10)
            .texOffs(60, 81).addBox(4, -1, -2, 1, 4, 4),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("rightArm").getChild("rightForearm").getChild("rightHand").addOrReplaceChild("halberd", CubeListBuilder.create()
            .texOffs(70, 81).addBox(-0.5f, -8, -0.5f, 1, 28, 1)
            .texOffs(74, 81).addBox(-0.5f, -14, -3, 1, 6, 6),
            PartPose.offsetAndRotation(0, 1, -1, -0.9f, 0, 0));
        return LayerDefinition.create(mesh, 128, 112);
    }
}
