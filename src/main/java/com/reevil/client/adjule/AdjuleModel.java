package com.reevil.client.adjule;

import com.reevil.ReEvilMod;
import com.reevil.client.cerberus.CerberusModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the CerberusModel rig, so all clips apply, with replaced/added parts. */
public class AdjuleModel extends CerberusModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "adjule"), "main");
    public AdjuleModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = CerberusModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("splitL", CubeListBuilder.create()
            .texOffs(0, 64).addBox(0, -1, -6, 3, 1, 8)
            .texOffs(22, 64).addBox(0, 0, -6, 3, 1, 8),
            PartPose.offsetAndRotation(1.5f, -3, -3, 0, 0, -0.9f));
        root.getChild("body").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("splitR", CubeListBuilder.create()
            .texOffs(0, 73).addBox(-3, -1, -6, 3, 1, 8)
            .texOffs(22, 73).addBox(-3, 0, -6, 3, 1, 8),
            PartPose.offsetAndRotation(-1.5f, -3, -3, 0, 0, 0.9f));
        root.getChild("body").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("plaga", CubeListBuilder.create()
            .texOffs(44, 73).addBox(-1.5f, -6, -7, 3, 5, 5)
            .texOffs(60, 73).addBox(-0.5f, -9, -7, 1, 4, 1)
            .texOffs(0, 83).addBox(-3, -6, -4, 1, 5, 1)
            .texOffs(4, 83).addBox(2, -6, -4, 1, 5, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 64, 96);
    }
}
