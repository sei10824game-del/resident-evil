package com.reevil.client.adjule;

import com.reevil.ReEvilMod;
import com.reevil.client.mrx.MrXModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the MrXModel rig, so all clips apply, with replaced/added parts. */
public class AdjuleModel extends MrXModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "adjule"), "main");
    public AdjuleModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = MrXModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("turban", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4.5f, -9, -4.5f, 9, 5, 9)
            .texOffs(36, 64).addBox(-4.5f, -5, -4.5f, 9, 2, 9)
            .texOffs(72, 64).addBox(-4, -4.5f, -4.6f, 8, 2.5f, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("cape", CubeListBuilder.create()
            .texOffs(90, 64).addBox(-5, 0, 0, 10, 16, 1)
            .texOffs(0, 81).addBox(-5, 0, 0.1f, 10, 2, 1),
            PartPose.offsetAndRotation(0, -10, 2.6f, 0.12f, 0, 0));
        return LayerDefinition.create(mesh, 128, 88);
    }
}
