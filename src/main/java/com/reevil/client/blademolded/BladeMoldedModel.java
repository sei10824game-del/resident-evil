package com.reevil.client.blademolded;

import com.reevil.ReEvilMod;
import com.reevil.client.ganado.GanadoModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GanadoModel rig, so all clips apply, with replaced/added parts. */
public class BladeMoldedModel extends GanadoModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "blade_molded"), "main");
    public BladeMoldedModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GanadoModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").addOrReplaceChild("shL", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-7, -12, -2, 3, 3, 4)
            .texOffs(14, 64).addBox(-9, -14, -1, 2, 4, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("shR", CubeListBuilder.create()
            .texOffs(22, 64).addBox(4, -12, -2, 3, 3, 4)
            .texOffs(36, 64).addBox(7, -14, -1, 2, 4, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 72);
    }
}
