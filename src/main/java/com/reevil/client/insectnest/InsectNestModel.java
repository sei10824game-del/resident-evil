package com.reevil.client.insectnest;

import com.reevil.ReEvilMod;
import com.reevil.client.ivy.IvyModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the IvyModel rig, so all clips apply, with replaced/added parts. */
public class InsectNestModel extends IvyModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "insect_nest"), "main");
    public InsectNestModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = IvyModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").addOrReplaceChild("hive", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-11, -18, -11, 22, 18, 22)
            .texOffs(0, 104).addBox(-8, -24, -8, 16, 7, 16)
            .texOffs(64, 104).addBox(-12, -10, -3, 2, 5, 5)
            .texOffs(78, 104).addBox(10, -12, 0, 2, 5, 5)
            .texOffs(92, 104).addBox(-3, -14, 10, 5, 5, 2)
            .texOffs(106, 104).addBox(-2, -20, -12, 5, 5, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 128);
    }
}
