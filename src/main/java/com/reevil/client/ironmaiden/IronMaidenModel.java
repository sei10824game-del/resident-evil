package com.reevil.client.ironmaiden;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class IronMaidenModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "iron_maiden"), "main");
    public IronMaidenModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("cage", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-6, -8, -4, 12, 10, 8)
            .texOffs(40, 64).addBox(-5, -7, -6.5f, 1, 1, 3)
            .texOffs(48, 64).addBox(-1, -7, -6.5f, 1, 1, 3)
            .texOffs(56, 64).addBox(3, -7, -6.5f, 1, 1, 3)
            .texOffs(64, 64).addBox(-3, -3, -6.5f, 1, 1, 3)
            .texOffs(72, 64).addBox(1, -3, -6.5f, 1, 1, 3)
            .texOffs(80, 64).addBox(-1, 0, -6.5f, 1, 1, 3),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("helm", CubeListBuilder.create()
            .texOffs(88, 64).addBox(-4.5f, -7, -4.5f, 9, 7, 9)
            .texOffs(0, 82).addBox(-3, -4, -4.6f, 6, 1, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
