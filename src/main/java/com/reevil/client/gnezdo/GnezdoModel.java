package com.reevil.client.gnezdo;

import com.reevil.ReEvilMod;
import com.reevil.client.larva.LarvaModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the LarvaModel rig, so all clips apply, with replaced/added parts. */
public class GnezdoModel extends LarvaModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "gnezdo"), "main");
    public GnezdoModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = LarvaModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("head").addOrReplaceChild("horn", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-0.5f, -6, -3, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("head").addOrReplaceChild("mandx", CubeListBuilder.create()
            .texOffs(4, 64).addBox(-2, -2, -8, 1, 1, 4)
            .texOffs(14, 64).addBox(1, -2, -8, 1, 1, 4),
            PartPose.ZERO);
        root.getChild("head").getChild("s1").addOrReplaceChild("bristle", CubeListBuilder.create()
            .texOffs(24, 64).addBox(-3.5f, -5, 2, 1, 2, 1)
            .texOffs(28, 64).addBox(2.5f, -5, 2, 1, 2, 1)
            .texOffs(32, 64).addBox(-0.5f, -6, 3, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("head").getChild("s1").getChild("s2").addOrReplaceChild("bristle", CubeListBuilder.create()
            .texOffs(36, 64).addBox(-3.5f, -5, 2, 1, 2, 1)
            .texOffs(40, 64).addBox(2.5f, -5, 2, 1, 2, 1)
            .texOffs(44, 64).addBox(-0.5f, -6, 3, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("head").getChild("s1").getChild("s2").getChild("s3").addOrReplaceChild("bristle", CubeListBuilder.create()
            .texOffs(48, 64).addBox(-3.5f, -5, 2, 1, 2, 1)
            .texOffs(52, 64).addBox(2.5f, -5, 2, 1, 2, 1)
            .texOffs(56, 64).addBox(-0.5f, -6, 3, 1, 3, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 64, 72);
    }
}
