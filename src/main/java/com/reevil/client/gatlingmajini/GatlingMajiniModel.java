package com.reevil.client.gatlingmajini;

import com.reevil.ReEvilMod;
import com.reevil.client.krauser.KrauserModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the KrauserModel rig, so all clips apply, with replaced/added parts. */
public class GatlingMajiniModel extends KrauserModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "gatling_majini"), "main");
    public GatlingMajiniModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = KrauserModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("gatling", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-2, -2, -4, 4, 4, 6)
            .texOffs(20, 64).addBox(-1.5f, -1.5f, -14, 1, 1, 10)
            .texOffs(42, 64).addBox(0.5f, -1.5f, -14, 1, 1, 10)
            .texOffs(64, 64).addBox(-0.5f, 0.5f, -14, 1, 1, 10)
            .texOffs(86, 64).addBox(-0.5f, -2.5f, -14, 1, 1, 10),
            PartPose.offsetAndRotation(0, 2, 0, -1.4f, 0, 0));
        root.getChild("base").getChild("torso").addOrReplaceChild("ammo", CubeListBuilder.create()
            .texOffs(0, 75).addBox(-4.6f, -9, -2.6f, 9.2f, 2, 5.2f)
            .texOffs(32, 75).addBox(-3, -7, 2.5f, 6, 6, 3),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
