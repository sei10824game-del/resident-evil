package com.reevil.client.jackbaker;

import com.reevil.ReEvilMod;
import com.reevil.client.mrx.MrXModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the MrXModel rig, so all clips apply, with replaced/added parts. */
public class JackBakerModel extends MrXModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "jack_baker"), "main");
    public JackBakerModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.mrx.MrXEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.mrx.SignatureClips.jack(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = MrXModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("shovel", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-0.6f, -4, -0.6f, 1.2f, 24, 1.2f)
            .texOffs(8, 64).addBox(-3, 19, -1, 6, 8, 1.5f)
            .texOffs(24, 64).addBox(-0.5f, 18, -1.2f, 1, 6, 2),
            PartPose.offsetAndRotation(0, 2, -1, -0.5f, 0, 0));
        root.getChild("base").getChild("torso").addOrReplaceChild("stains", CubeListBuilder.create()
            .texOffs(30, 64).addBox(-4.6f, -10, -2.6f, 9.2f, 5, 5.2f),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
