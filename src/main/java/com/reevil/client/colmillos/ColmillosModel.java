package com.reevil.client.colmillos;

import com.reevil.ReEvilMod;
import com.reevil.client.cerberus.CerberusModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the CerberusModel rig, so all clips apply, with replaced/added parts. */
public class ColmillosModel extends CerberusModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "colmillos"), "main");
    public ColmillosModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = CerberusModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("chest").addOrReplaceChild("spines", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-1, -6, -9, 2, 3, 2)
            .texOffs(8, 64).addBox(-1, -6, -6, 2, 4, 2)
            .texOffs(16, 64).addBox(-1, -6, -3, 2, 3, 2),
            PartPose.ZERO);
        root.getChild("body").getChild("hips").addOrReplaceChild("spines2", CubeListBuilder.create()
            .texOffs(24, 64).addBox(-1, -5, 0, 2, 3, 2)
            .texOffs(32, 64).addBox(-1, -5, 3, 2, 3, 2),
            PartPose.ZERO);
        root.getChild("body").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("horns", CubeListBuilder.create()
            .texOffs(40, 64).addBox(-2.5f, -5, -3, 1, 3, 1)
            .texOffs(44, 64).addBox(1.5f, -5, -3, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("tent", CubeListBuilder.create()
            .texOffs(48, 64).addBox(-2, 1, -9, 1, 1, 6)
            .texOffs(0, 71).addBox(1, 1, -9, 1, 1, 6),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 64, 80);
    }
}
