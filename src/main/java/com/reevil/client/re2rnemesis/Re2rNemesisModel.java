package com.reevil.client.re2rnemesis;

import com.reevil.ReEvilMod;
import com.reevil.client.nemesis.NemesisModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the NemesisModel rig, so all clips apply, with replaced/added parts. */
public class Re2rNemesisModel extends NemesisModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re2r_nemesis"), "main");
    public Re2rNemesisModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = NemesisModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").addOrReplaceChild("muscle", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-5.5f, -11, -3, 11, 7, 6),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("jaw", CubeListBuilder.create()
            .texOffs(34, 64).addBox(-3.7f, -3, -4, 7.4f, 3, 1.5f)
            .texOffs(54, 64).addBox(-3.7f, -3.2f, -4.6f, 7.4f, 1, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("mgun", CubeListBuilder.create()
            .texOffs(72, 64).addBox(-1.2f, -1.5f, -9, 2.4f, 3, 10)
            .texOffs(98, 64).addBox(-0.8f, 1.5f, -3, 1.6f, 4, 2)
            .texOffs(106, 64).addBox(-0.5f, -0.5f, -14, 1, 1, 5)
            .texOffs(0, 77).addBox(-1.4f, -1, -1, 2.8f, 2, 3),
            PartPose.offsetAndRotation(0, 2, -1, -1.5f, 0, 0));
        return LayerDefinition.create(mesh, 128, 88);
    }
}
