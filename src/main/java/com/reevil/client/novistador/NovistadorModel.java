package com.reevil.client.novistador;

import com.reevil.ReEvilMod;
import com.reevil.client.giantmoth.GiantMothModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GiantMothModel rig, so all clips apply, with replaced/added parts. */
public class NovistadorModel extends GiantMothModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "novistador"), "main");
    public NovistadorModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GiantMothModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").addOrReplaceChild("spines", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-0.5f, -5, -3, 1, 3, 1)
            .texOffs(4, 64).addBox(-0.5f, -5, 0, 1, 4, 1)
            .texOffs(8, 64).addBox(-0.5f, -4, 3, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("head").addOrReplaceChild("mand", CubeListBuilder.create()
            .texOffs(12, 64).addBox(-2.5f, 0, -5.5f, 1, 1, 4)
            .texOffs(22, 64).addBox(1.5f, 0, -5.5f, 1, 1, 4),
            PartPose.ZERO);
        root.getChild("body").addOrReplaceChild("clawL", CubeListBuilder.create()
            .texOffs(32, 64).addBox(-0.5f, 0, -0.5f, 1, 8, 1)
            .texOffs(36, 64).addBox(-1, 7, -1, 2, 1, 3),
            PartPose.offsetAndRotation(2, 2, -3, -0.6f, 0.2f, 0));
        root.getChild("body").addOrReplaceChild("clawR", CubeListBuilder.create()
            .texOffs(46, 64).addBox(-0.5f, 0, -0.5f, 1, 8, 1)
            .texOffs(50, 64).addBox(-1, 7, -1, 2, 1, 3),
            PartPose.offsetAndRotation(-2, 2, -3, -0.6f, -0.2f, 0));
        return LayerDefinition.create(mesh, 128, 80);
    }
}
