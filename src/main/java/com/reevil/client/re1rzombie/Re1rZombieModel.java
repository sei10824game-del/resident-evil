package com.reevil.client.re1rzombie;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class Re1rZombieModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re1r_zombie"), "main");
    public Re1rZombieModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.zombie.ZombieEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.remake.RemakeClips.re1r_zombie(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("ribs", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -5, -3, 8, 1, 1)
            .texOffs(18, 64).addBox(-4, -3, -3, 8, 1, 1)
            .texOffs(36, 64).addBox(-4, -1, -3, 8, 1, 1)
            .texOffs(54, 64).addBox(-4.6f, -6, -2.6f, 9.2f, 2, 5.2f),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("rags", CubeListBuilder.create()
            .texOffs(86, 64).addBox(-4.7f, -6, -2.7f, 4, 6, 5.4f)
            .texOffs(106, 64).addBox(1.5f, -3, -2.7f, 3.2f, 4, 5.4f)
            .texOffs(0, 76).addBox(-3, 0, -2.2f, 6, 5, 4.4f),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("wound", CubeListBuilder.create()
            .texOffs(22, 76).addBox(-4.2f, -6, -4.2f, 3, 3, 8.4f)
            .texOffs(46, 76).addBox(-1, -7.5f, -2, 4, 2, 4),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
