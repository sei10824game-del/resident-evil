package com.reevil.client.ustanak;

import com.reevil.ReEvilMod;
import com.reevil.client.mrx.MrXModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the MrXModel rig, so all clips apply, with replaced/added parts. */
public class UstanakModel extends MrXModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "ustanak"), "main");
    public UstanakModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = MrXModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").addOrReplaceChild("plate", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-5, -10.5f, -3, 10, 6, 1)
            .texOffs(22, 64).addBox(-8, -12, -3, 4, 4, 6)
            .texOffs(42, 64).addBox(4, -12, -3, 4, 4, 6)
            .texOffs(62, 64).addBox(-4.5f, -4, -3, 9, 3, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("mask", CubeListBuilder.create()
            .texOffs(82, 64).addBox(-4, -7.5f, -4.4f, 8, 5, 1.2f)
            .texOffs(102, 64).addBox(-3, -4.5f, -4.8f, 6, 1, 1)
            .texOffs(0, 74).addBox(-4.5f, -8, -4.5f, 9, 2, 9),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
