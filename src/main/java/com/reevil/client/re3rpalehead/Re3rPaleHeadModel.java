package com.reevil.client.re3rpalehead;

import com.reevil.ReEvilMod;
import com.reevil.client.palehead.PaleHeadModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the PaleHeadModel rig, so all clips apply, with replaced/added parts. */
public class Re3rPaleHeadModel extends PaleHeadModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re3r_pale_head"), "main");
    public Re3rPaleHeadModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.zombie.ZombieEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.remake.RemakeClips.re3r_pale_head(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = PaleHeadModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("dome", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-3, -13, -3, 6, 8, 6)
            .texOffs(24, 64).addBox(-3.5f, -9, -3.5f, 7, 2, 7),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("spines", CubeListBuilder.create()
            .texOffs(52, 64).addBox(-1, -6, 2.5f, 2, 3, 2)
            .texOffs(60, 64).addBox(-1, -3, 2.5f, 2, 3, 2)
            .texOffs(68, 64).addBox(-4, -5, 2.5f, 2, 3, 2)
            .texOffs(76, 64).addBox(2, -5, 2.5f, 2, 3, 2)
            .texOffs(84, 64).addBox(-4.6f, -5.5f, -2.7f, 9.2f, 1, 5.4f)
            .texOffs(0, 78).addBox(-4.6f, -3.5f, -2.7f, 9.2f, 1, 5.4f),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
