package com.reevil.client.re4rregenerador;

import com.reevil.ReEvilMod;
import com.reevil.client.regenerador.RegeneradorModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the RegeneradorModel rig, so all clips apply, with replaced/added parts. */
public class Re4rRegeneradorModel extends RegeneradorModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re4r_regenerador"), "main");
    public Re4rRegeneradorModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = RegeneradorModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("mask", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-3.8f, -3.5f, -4.3f, 7.6f, 3.5f, 2)
            .texOffs(20, 64).addBox(-1, -3, -5.5f, 2, 2, 2)
            .texOffs(28, 64).addBox(-3, -7, -4.3f, 6, 1, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("maw", CubeListBuilder.create()
            .texOffs(42, 64).addBox(-3.5f, -5, -3.3f, 7, 5, 1)
            .texOffs(58, 64).addBox(-4, -6, -3.2f, 8, 1, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("spine", CubeListBuilder.create()
            .texOffs(76, 64).addBox(-1, -6, 2.5f, 2, 3, 2)
            .texOffs(84, 64).addBox(-1, -3, 2.5f, 2, 3, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 72);
    }
}
