package com.reevil.client.re2rlicker;

import com.reevil.ReEvilMod;
import com.reevil.client.licker.LickerModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the LickerModel rig, so all clips apply, with replaced/added parts. */
public class Re2rLickerModel extends LickerModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re2r_licker"), "main");
    public Re2rLickerModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = LickerModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").addOrReplaceChild("spikes", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-1, -7, -9, 2, 4, 2)
            .texOffs(8, 64).addBox(-1, -7, -6, 2, 5, 2)
            .texOffs(16, 64).addBox(-1, -7, -3, 2, 6, 2)
            .texOffs(24, 64).addBox(-1, -6, 0, 2, 5, 2)
            .texOffs(32, 64).addBox(-4.5f, -5, -4, 2, 3, 2)
            .texOffs(40, 64).addBox(2.5f, -5, -4, 2, 3, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("muscle", CubeListBuilder.create()
            .texOffs(48, 64).addBox(-5, -4.5f, -10.5f, 10, 8, 11),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("armL").getChild("foreL").getChild("handL").addOrReplaceChild("blade", CubeListBuilder.create()
            .texOffs(90, 64).addBox(-0.5f, 0, -1, 1, 10, 1)
            .texOffs(94, 64).addBox(-2, 0, -1, 1, 9, 1),
            PartPose.offsetAndRotation(0, 2, -1, 0.3f, 0, 0));
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("blade", CubeListBuilder.create()
            .texOffs(98, 64).addBox(-0.5f, 0, -1, 1, 10, 1)
            .texOffs(102, 64).addBox(1, 0, -1, 1, 9, 1),
            PartPose.offsetAndRotation(0, 2, -1, 0.3f, 0, 0));
        root.getChild("base").getChild("torso").getChild("neck1").getChild("neck2").getChild("head").addOrReplaceChild("brain", CubeListBuilder.create()
            .texOffs(0, 83).addBox(-3.5f, -8, -7, 7, 3, 6),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
