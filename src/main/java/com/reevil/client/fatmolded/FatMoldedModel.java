package com.reevil.client.fatmolded;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class FatMoldedModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "fat_molded"), "main");
    public FatMoldedModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("belly", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-6.5f, -4, -4.5f, 13, 10, 9)
            .texOffs(44, 64).addBox(-3, -6, -5, 6, 3, 3),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("lump", CubeListBuilder.create()
            .texOffs(62, 64).addBox(-3, -8, -3, 6, 3, 6)
            .texOffs(86, 64).addBox(2, -6, -4.5f, 3, 4, 3),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("spikes", CubeListBuilder.create()
            .texOffs(98, 64).addBox(-5, -7, 2.5f, 2, 4, 3)
            .texOffs(108, 64).addBox(-1, -8, 2.5f, 2, 5, 3)
            .texOffs(118, 64).addBox(3, -7, 2.5f, 2, 4, 3),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 88);
    }
}
