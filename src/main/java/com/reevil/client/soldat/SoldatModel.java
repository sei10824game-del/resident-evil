package com.reevil.client.soldat;

import com.reevil.ReEvilMod;
import com.reevil.client.krauser.KrauserModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the KrauserModel rig, so all clips apply, with replaced/added parts. */
public class SoldatModel extends KrauserModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "soldat"), "main");
    public SoldatModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = KrauserModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("helm", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -8, -4, 8, 4, 8)
            .texOffs(32, 64).addBox(-3, -5, -4.4f, 6, 3, 1)
            .texOffs(46, 64).addBox(-2, -3, -5, 4, 3, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("vest", CubeListBuilder.create()
            .texOffs(58, 64).addBox(-4.6f, -10, -2.6f, 9.2f, 8, 5.2f)
            .texOffs(90, 64).addBox(-3, -9, -2.9f, 2, 2, 1)
            .texOffs(96, 64).addBox(1, -9, -2.9f, 2, 2, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
