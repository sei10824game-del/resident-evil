package com.reevil.client.re2rzombie;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class Re2rZombieModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re2r_zombie"), "main");
    public Re2rZombieModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.zombie.ZombieEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.remake.RemakeClips.re2r_zombie(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("cap", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4.5f, -7.5f, -4.5f, 9, 2, 9)
            .texOffs(36, 64).addBox(-4.5f, -6, -6.5f, 9, 1, 3)
            .texOffs(60, 64).addBox(-1.5f, -7, -4.7f, 3, 1.5f, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("vest", CubeListBuilder.create()
            .texOffs(68, 64).addBox(-5, -6.2f, -3, 10, 6.2f, 6)
            .texOffs(100, 64).addBox(-4, -4, -3.2f, 3, 1.5f, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("ribs", CubeListBuilder.create()
            .texOffs(108, 64).addBox(-4, -1, -3.2f, 8, 1, 1),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
