package com.reevil.client.gravedigger;

import com.reevil.ReEvilMod;
import com.reevil.client.yawn.YawnModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the YawnModel rig, so all clips apply, with replaced/added parts. */
public class GraveDiggerModel extends YawnModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "grave_digger"), "main");
    public GraveDiggerModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = YawnModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("neck1").getChild("neck2").getChild("neck3").getChild("head").addOrReplaceChild("hornsX", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-3, -5, -6, 1, 3, 1)
            .texOffs(4, 64).addBox(2, -5, -6, 1, 3, 1)
            .texOffs(8, 64).addBox(-0.5f, -6, -3, 1, 4, 1),
            PartPose.ZERO);
        root.getChild("body").addOrReplaceChild("spk", CubeListBuilder.create()
            .texOffs(12, 64).addBox(-1, -8, -4, 2, 3, 2)
            .texOffs(20, 64).addBox(-1, -8, 0, 2, 3, 2)
            .texOffs(28, 64).addBox(-1, -8, 4, 2, 3, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 256, 72);
    }
}
