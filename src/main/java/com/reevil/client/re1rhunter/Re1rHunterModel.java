package com.reevil.client.re1rhunter;

import com.reevil.ReEvilMod;
import com.reevil.client.hunter.HunterModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the HunterModel rig, so all clips apply, with replaced/added parts. */
public class Re1rHunterModel extends HunterModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re1r_hunter"), "main");
    public Re1rHunterModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = HunterModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("hips").getChild("chest").addOrReplaceChild("plates", CubeListBuilder.create()
            .texOffs(0, 128).addBox(-6, -15, -3, 12, 3, 6)
            .texOffs(36, 128).addBox(-4, -12, 4, 8, 3, 3)
            .texOffs(58, 128).addBox(-3, -9, 4, 6, 3, 3)
            .texOffs(76, 128).addBox(-2, -6, 4, 4, 3, 3)
            .texOffs(90, 128).addBox(-8, -14, -2, 3, 3, 4)
            .texOffs(104, 128).addBox(5, -14, -2, 3, 3, 4),
            PartPose.ZERO);
        root.getChild("base").getChild("hips").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("crest", CubeListBuilder.create()
            .texOffs(0, 137).addBox(-1.5f, -8, -3, 3, 4, 5)
            .texOffs(16, 137).addBox(-4, -5.5f, -5.5f, 2, 2, 3)
            .texOffs(26, 137).addBox(2, -5.5f, -5.5f, 2, 2, 3),
            PartPose.ZERO);
        root.getChild("base").getChild("hips").getChild("chest").getChild("armL").getChild("foreL").getChild("handL").addOrReplaceChild("boneL", CubeListBuilder.create()
            .texOffs(36, 137).addBox(-0.5f, 0, -1, 1, 8, 1)
            .texOffs(40, 137).addBox(1, 0, -1, 1, 7, 1),
            PartPose.offsetAndRotation(0, 3, -2, -0.35f, 0, 0));
        root.getChild("base").getChild("hips").getChild("chest").getChild("armR").getChild("foreR").getChild("handR").addOrReplaceChild("boneR", CubeListBuilder.create()
            .texOffs(44, 137).addBox(-0.5f, 0, -1, 1, 8, 1)
            .texOffs(48, 137).addBox(-2, 0, -1, 1, 7, 1),
            PartPose.offsetAndRotation(0, 3, -2, -0.35f, 0, 0));
        return LayerDefinition.create(mesh, 128, 152);
    }
}
