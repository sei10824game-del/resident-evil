package com.reevil.client.re4rverdugo;

import com.reevil.ReEvilMod;
import com.reevil.client.verdugo.VerdugoModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the VerdugoModel rig, so all clips apply, with replaced/added parts. */
public class Re4rVerdugoModel extends VerdugoModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re4r_verdugo"), "main");
    public Re4rVerdugoModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.mrx.MrXEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.remake.RemakeClips.re4r_verdugo(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = VerdugoModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("hood", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -8.5f, -1, 8, 9, 5)
            .texOffs(26, 64).addBox(-4, -8.5f, -4, 1.5f, 7, 4)
            .texOffs(38, 64).addBox(2.5f, -8.5f, -4, 1.5f, 7, 4)
            .texOffs(50, 64).addBox(-3.5f, -9.5f, -4, 7, 1.5f, 6),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("maskb", CubeListBuilder.create()
            .texOffs(76, 64).addBox(-3, -6, -4.3f, 6, 4, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("ribs", CubeListBuilder.create()
            .texOffs(90, 64).addBox(-4.8f, -9, -2.6f, 9.6f, 1, 5.2f)
            .texOffs(0, 78).addBox(-4.8f, -6.5f, -2.6f, 9.6f, 1, 5.2f)
            .texOffs(32, 78).addBox(-4.8f, -4, -2.6f, 9.6f, 1, 5.2f)
            .texOffs(64, 78).addBox(-6.5f, -11, -2, 3, 3, 4)
            .texOffs(78, 78).addBox(3.5f, -11, -2, 3, 3, 4),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("armR").getChild("foreR").addOrReplaceChild("blade", CubeListBuilder.create()
            .texOffs(92, 78).addBox(-0.5f, 1, -3, 1, 14, 3),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("armL").getChild("foreL").addOrReplaceChild("blade", CubeListBuilder.create()
            .texOffs(100, 78).addBox(-0.5f, 1, -3, 1, 14, 3),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
