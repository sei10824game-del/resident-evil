package com.reevil.client.armadura;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class ArmaduraModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "armadura"), "main");
    public ArmaduraModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("helm", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4.5f, -7, -4.5f, 9, 7, 9)
            .texOffs(36, 64).addBox(-1, -9, -4, 2, 3, 8)
            .texOffs(56, 64).addBox(-3, -4, -4.6f, 6, 1, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("plate", CubeListBuilder.create()
            .texOffs(70, 64).addBox(-5, -6, -3, 10, 6, 1)
            .texOffs(92, 64).addBox(-5, -6, 2, 10, 6, 1)
            .texOffs(0, 80).addBox(-7.5f, -7, -3, 3, 3, 6)
            .texOffs(18, 80).addBox(4.5f, -7, -3, 3, 3, 6),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").addOrReplaceChild("skirt", CubeListBuilder.create()
            .texOffs(36, 80).addBox(-4.5f, 0, -2.5f, 9, 3, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 96);
    }
}
