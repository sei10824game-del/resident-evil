package com.reevil.client.re4rganado;

import com.reevil.ReEvilMod;
import com.reevil.client.ganado.GanadoModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the GanadoModel rig, so all clips apply, with replaced/added parts. */
public class Re4rGanadoModel extends GanadoModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re4r_ganado"), "main");
    public Re4rGanadoModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GanadoModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("bandana", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -5.5f, -4.2f, 8, 2, 8.4f)
            .texOffs(34, 64).addBox(-1, -5.5f, 3.5f, 2, 4, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("beard", CubeListBuilder.create()
            .texOffs(40, 64).addBox(-3.6f, -2, -3.8f, 7.2f, 3, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("pack", CubeListBuilder.create()
            .texOffs(58, 64).addBox(-3.5f, -9, 2.3f, 7, 8, 3)
            .texOffs(78, 64).addBox(-3, -10, 2.8f, 6, 1, 2),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("vest", CubeListBuilder.create()
            .texOffs(94, 64).addBox(-4.5f, -9.5f, -2.5f, 9, 8, 5),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 80);
    }
}
