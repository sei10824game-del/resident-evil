package com.reevil.client.re2rmrx;

import com.reevil.ReEvilMod;
import com.reevil.client.mrx.MrXModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the MrXModel rig, so all clips apply, with replaced/added parts. */
public class Re2rMrXModel extends MrXModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "re2r_mr_x"), "main");
    public Re2rMrXModel(ModelPart root) { super(root); }
    @Override
    protected com.reevil.anim.AnimClip clip(com.reevil.entity.mrx.MrXEntity e, int id) {
        com.reevil.anim.AnimClip c = com.reevil.client.remake.RemakeClips.re2r_mr_x(id);
        return c != null ? c : super.clip(e, id);
    }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = MrXModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("hat", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-6.5f, -7.5f, -6.5f, 13, 1, 13)
            .texOffs(52, 64).addBox(-4, -11, -4, 8, 4, 8)
            .texOffs(84, 64).addBox(-4.1f, -8, -4.1f, 8.2f, 1, 8.2f),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").getChild("neck").getChild("head").addOrReplaceChild("scars", CubeListBuilder.create()
            .texOffs(0, 78).addBox(-3.6f, -5, -3.9f, 7.2f, 1, 1)
            .texOffs(18, 78).addBox(-1, -3, -3.9f, 1, 3, 1),
            PartPose.ZERO);
        root.getChild("base").getChild("torso").addOrReplaceChild("collar", CubeListBuilder.create()
            .texOffs(22, 78).addBox(-6, -11.5f, -3.5f, 12, 3, 7)
            .texOffs(60, 78).addBox(-5.5f, -9, -3, 11, 8, 6),
            PartPose.ZERO);
        root.getChild("base").getChild("thighL").addOrReplaceChild("coatL", CubeListBuilder.create()
            .texOffs(94, 78).addBox(-3.2f, -1, -3.8f, 6.4f, 17, 7.6f),
            PartPose.ZERO);
        root.getChild("base").getChild("thighR").addOrReplaceChild("coatR", CubeListBuilder.create()
            .texOffs(0, 103).addBox(-3.2f, -1, -3.8f, 6.4f, 17, 7.6f),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 128);
    }
}
