/** Own silhouette (generated by tools/variantgen.py): the GiantMothModel rig, so all clips apply, with replaced/added parts. */
public class MargueriteModel extends GiantMothModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "marguerite"), "main");
    public MargueriteModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = GiantMothModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("head").addOrReplaceChild("face", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-2.2f, -2.2f, -4.4f, 4.4f, 4.4f, 1)
            .texOffs(12, 64).addBox(-2.7f, -3, -2, 5.4f, 3, 5),
            PartPose.ZERO);
        root.getChild("body").getChild("abdomen").addOrReplaceChild("sac", CubeListBuilder.create()
            .texOffs(34, 64).addBox(-4, -4, 5, 8, 8, 6)
            .texOffs(62, 64).addBox(-3, -3, -1, 6, 6, 2),
            PartPose.ZERO);
        root.getChild("body").addOrReplaceChild("xlegL0", CubeListBuilder.create()
            .texOffs(78, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(2.5f, 1, -2, 0.2f, 0, 0.9f));
        root.getChild("body").addOrReplaceChild("xlegL1", CubeListBuilder.create()
            .texOffs(82, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(2.5f, 1, 0, 0.2f, 0, 0.9f));
        root.getChild("body").addOrReplaceChild("xlegL2", CubeListBuilder.create()
            .texOffs(86, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(2.5f, 1, 2, 0.2f, 0, 0.9f));
        root.getChild("body").addOrReplaceChild("xlegL3", CubeListBuilder.create()
            .texOffs(90, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(2.5f, 1, 4, 0.2f, 0, 0.9f));
        root.getChild("body").addOrReplaceChild("xlegR0", CubeListBuilder.create()
            .texOffs(94, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(-2.5f, 1, -2, 0.2f, 0, -0.9f));
        root.getChild("body").addOrReplaceChild("xlegR1", CubeListBuilder.create()
            .texOffs(98, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(-2.5f, 1, 0, 0.2f, 0, -0.9f));
        root.getChild("body").addOrReplaceChild("xlegR2", CubeListBuilder.create()
            .texOffs(102, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(-2.5f, 1, 2, 0.2f, 0, -0.9f));
        root.getChild("body").addOrReplaceChild("xlegR3", CubeListBuilder.create()
            .texOffs(106, 64).addBox(-0.5f, 0, -0.5f, 1, 9, 1),
            PartPose.offsetAndRotation(-2.5f, 1, 4, 0.2f, 0, -0.9f));
        return LayerDefinition.create(mesh, 128, 80);
    }
}
