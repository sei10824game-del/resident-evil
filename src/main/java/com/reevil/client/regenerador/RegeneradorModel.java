package com.reevil.client.regenerador;

import com.reevil.ReEvilMod;
import com.reevil.client.zombie.ZombieModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;

/** Own silhouette (generated by tools/variantgen.py): the ZombieModel rig, so all clips apply, with replaced/added parts. */
public class RegeneradorModel extends ZombieModel {
    public static final ModelLayerLocation LAYER = new ModelLayerLocation(new ResourceLocation(ReEvilMod.MODID, "regenerador"), "main");
    public RegeneradorModel(ModelPart root) { super(root); }
    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = ZombieModel.mesh();
        PartDefinition root = mesh.getRoot();
        root.getChild("body").getChild("waist").getChild("chest").addOrReplaceChild("ribs", CubeListBuilder.create()
            .texOffs(0, 64).addBox(-4, -5, -3, 8, 1, 1)
            .texOffs(18, 64).addBox(-4, -3, -3, 8, 1, 1)
            .texOffs(36, 64).addBox(-4, -1, -3, 8, 1, 1)
            .texOffs(54, 64).addBox(-2, -4, -3.2f, 4, 3, 1),
            PartPose.ZERO);
        root.getChild("body").getChild("waist").getChild("chest").getChild("neck").getChild("head").addOrReplaceChild("crown", CubeListBuilder.create()
            .texOffs(64, 64).addBox(-3, -8, -3, 6, 2, 6)
            .texOffs(88, 64).addBox(-1, -10, -1, 2, 3, 2),
            PartPose.ZERO);
        return LayerDefinition.create(mesh, 128, 72);
    }
}
